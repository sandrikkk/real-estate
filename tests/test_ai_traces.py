"""AI-attribution guard: detector rules, the three hook modes, and a whole-repo invariant."""

import importlib.util
import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SCRIPT = REPO_ROOT / "scripts" / "git" / "check_ai_traces.py"

_spec = importlib.util.spec_from_file_location("check_ai_traces", SCRIPT)
guard = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(guard)

TRACES = [
    "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "Generated with Claude Code",
    "Generated by ChatGPT",
    "generated using GitHub Copilot",
    "Written by an AI assistant",
    "Created with Cursor",
    "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
    "co-authored-by: Someone <someone@example.com>",
    "Claude-Session: https://claude.ai/code/session_abc",
    "see https://claude.ai/code/abc for the transcript",
    "contact noreply@anthropic.com",
]

ORDINARY = [
    "Generated with ruff format",
    "The report is generated by the scraper every 15 minutes",
    "Created with a 50-item chunk size",
    "authored by the repository owner",
    "The claude-api skill documents model ids",
    "Pre-commit hooks reject bad commit messages",
    "fix(xray): stop matching flats on missing evidence",
    "",
]


def run_script(*args, stdin="", cwd=None):
    return subprocess.run(
        [sys.executable, str(SCRIPT), *args],
        input=stdin,
        capture_output=True,
        text=True,
        encoding="utf-8",
        cwd=cwd,
    )


def hook_payload(command, cwd=None):
    payload = {"tool_name": "Bash", "tool_input": {"command": command}}
    if cwd:
        payload["cwd"] = str(cwd)
    return json.dumps(payload)


class TestDetector(unittest.TestCase):
    def test_flags_attribution_signatures(self):
        for text in TRACES:
            with self.subTest(text=text):
                self.assertTrue(guard.find_traces(text), text)

    def test_ignores_ordinary_text(self):
        for text in ORDINARY:
            with self.subTest(text=text):
                self.assertEqual(guard.find_traces(text), [])

    def test_reports_line_numbers(self):
        hits = guard.find_traces("## Merging\n\nNothing here\n🤖 Generated with Claude Code\n")
        self.assertEqual([number for number, _, _ in hits], [4])


class TestCommitMsgHook(unittest.TestCase):
    def run_on(self, message):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp) / "COMMIT_EDITMSG"
            path.write_text(message, encoding="utf-8")
            return run_script("commit-msg", str(path))

    def test_rejects_message_with_trace(self):
        result = self.run_on("fix(xray): x\n\nbody\n\nGenerated with Claude Code\n")
        self.assertEqual(result.returncode, 1)
        self.assertIn("line 5", result.stderr)

    def test_accepts_clean_message(self):
        self.assertEqual(self.run_on("fix(xray): x\n\nbody\n").returncode, 0)

    def test_ignores_git_comment_lines(self):
        self.assertEqual(self.run_on("fix: x\n\n# Co-authored-by: example\n").returncode, 0)


class TestStagedHook(unittest.TestCase):
    def stage(self, files):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        root = Path(tmp.name)
        subprocess.run(["git", "init", "-q"], cwd=root, check=True)
        for name, text in files.items():
            target = root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")
        subprocess.run(["git", "add", "-A"], cwd=root, check=True, capture_output=True)
        return root

    def test_rejects_added_trace(self):
        root = self.stage({"notes.md": "ok\nGenerated by ChatGPT\n"})
        result = run_script("staged", cwd=root)
        self.assertEqual(result.returncode, 1)
        self.assertIn("notes.md", result.stderr)

    def test_accepts_clean_files(self):
        root = self.stage({"notes.md": "ok\n", "src/app.py": "print('hi')\n"})
        self.assertEqual(run_script("staged", cwd=root).returncode, 0)

    def test_allows_policy_files_to_spell_patterns_out(self):
        root = self.stage({".agents/skills/no-ai-traces/SKILL.md": "Generated with Claude Code\n"})
        self.assertEqual(run_script("staged", cwd=root).returncode, 0)


class TestClaudeHook(unittest.TestCase):
    def test_blocks_commit_message_with_trace(self):
        command = 'git commit -m "fix: x\n\nGenerated with Claude Code"'
        self.assertEqual(run_script("claude-hook", stdin=hook_payload(command)).returncode, 2)

    def test_blocks_pr_body_with_trace(self):
        command = 'gh pr create --title "t" --body "text\n🤖 Generated with Claude Code"'
        self.assertEqual(run_script("claude-hook", stdin=hook_payload(command)).returncode, 2)

    def test_blocks_trace_inside_body_file(self):
        with tempfile.TemporaryDirectory() as tmp:
            body = Path(tmp) / "pr_body.md"
            body.write_text("## Problem\n\n🤖 Generated with [Claude Code](x)\n", encoding="utf-8")
            command = f'gh pr create --body-file "{body}"'
            result = run_script("claude-hook", stdin=hook_payload(command))
        self.assertEqual(result.returncode, 2)
        self.assertIn("pr_body.md", result.stderr)

    def test_resolves_relative_body_file_against_cwd(self):
        with tempfile.TemporaryDirectory() as tmp:
            Path(tmp, "body.md").write_text("Created with Cursor\n", encoding="utf-8")
            command = "gh pr edit 1 --body-file body.md"
            result = run_script("claude-hook", stdin=hook_payload(command, cwd=tmp))
        self.assertEqual(result.returncode, 2)

    def test_allows_clean_publishing_commands(self):
        for command in (
            'git commit -m "fix(xray): stop matching flats on missing evidence"',
            'gh pr create --title "t" --body "## Problem\\nclean"',
        ):
            with self.subTest(command=command):
                self.assertEqual(
                    run_script("claude-hook", stdin=hook_payload(command)).returncode, 0
                )

    def test_ignores_commands_that_publish_nothing(self):
        for command in ("ls -la", 'echo "Generated with Claude Code"', "git status"):
            with self.subTest(command=command):
                self.assertEqual(
                    run_script("claude-hook", stdin=hook_payload(command)).returncode, 0
                )

    def test_ignores_malformed_input(self):
        self.assertEqual(run_script("claude-hook", stdin="not json").returncode, 0)
        self.assertEqual(run_script("claude-hook", stdin="{}").returncode, 0)


class TestRepositoryIsClean(unittest.TestCase):
    def test_no_tracked_file_contains_a_trace(self):
        listing = subprocess.run(
            ["git", "ls-files", "-z"], cwd=REPO_ROOT, capture_output=True, check=True
        ).stdout.decode("utf-8")
        offenders = []
        for name in filter(None, listing.split("\0")):
            if name in guard.ALLOWED_PATHS:
                continue
            path = REPO_ROOT / name
            try:
                if not path.is_file() or path.stat().st_size > guard.MAX_FILE_BYTES:
                    continue
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            for number, rule, line in guard.find_traces(text):
                offenders.append(f"{name}:{number} [{rule}] {line}")
        self.assertEqual(offenders, [])


